"""Generate src/layout/iconImages.ts: each panel icon as a PNG data URI.

    python scripts/gen_icons.py

Source is tools/icon_masks.py, the alpha masks generated alongside the
firmware's icon fonts by tools/make_icon_font.sh - so the designer shows
the same glyphs the panel draws. The PNGs are white with the glyph in the
alpha channel; the app uses them as CSS masks, so they take the text
colour of whichever theme the app is in. Rerun after make_icon_font.sh.
"""
import base64
import io
import sys
from pathlib import Path

from PIL import Image

here = Path(__file__).resolve().parent
root = here.parent.parent
sys.path.insert(0, str(root / "tools"))
import icon_masks  # noqa: E402

SIZE = 36
names = sorted({k.rsplit("_", 1)[0] for k in icon_masks._MASKS})
lines = ["// Generated by scripts/gen_icons.py from tools/icon_masks.py - do not edit.",
         "// Each panel icon as a white PNG whose alpha is the glyph; used as a CSS mask.",
         "export const ICON_IMAGES: Record<string, string> = {"]
for n in names:
    a = icon_masks.mask(n, SIZE)
    img = Image.frombytes("L", (SIZE, SIZE), bytes(a))
    rgba = Image.new("RGBA", (SIZE, SIZE), (255, 255, 255, 0))
    rgba.putalpha(img)
    buf = io.BytesIO()
    rgba.save(buf, "PNG", optimize=True)
    lines.append(f'  {n}: "data:image/png;base64,{base64.b64encode(buf.getvalue()).decode()}",')
lines.append("};")
out = here.parent / "src" / "layout" / "iconImages.ts"
out.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"wrote {out} ({len(names)} icons, {out.stat().st_size // 1024} KB)")
