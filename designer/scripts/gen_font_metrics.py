"""Generate src/layout/fontMetrics.ts from the panel's 14 px name font.

    python scripts/gen_font_metrics.py

Reads LVGL's lv_font_montserrat_14.c (PlatformIO's copy) - the font tile
names are drawn in - and records each glyph's advance width, so the
designer can say exactly how a name will be cut, and which characters the
panel cannot draw at all. The font has printable ASCII and the degree
sign (plus LVGL's private-use symbols, irrelevant to names).
"""
import re
from pathlib import Path

here = Path(__file__).resolve().parent
src = (here.parents[1] / ".pio" / "libdeps" / "ha" / "lvgl" / "src" / "font" / "lv_font_montserrat_14.c").read_text(encoding="utf-8")
adv = [int(x) for x in re.findall(r"\.adv_w = (\d+)", src[src.index("glyph_dsc[] = {"):])]
# glyph id 1.. covers 32..126; the degree sign is the first glyph of the second range.
widths = {cp: adv[cp - 32 + 1] / 16 for cp in range(32, 127)}
widths[0xB0] = adv[96] / 16
line = ",".join(f"{cp}:{w:g}" for cp, w in sorted(widths.items()))
out = here.parent / "src" / "layout" / "fontMetrics.ts"
out.write_text(
    "// Generated by scripts/gen_font_metrics.py from LVGL's lv_font_montserrat_14.c - do not edit.\n"
    "// Advance widths in pixels of the font tile names are drawn in, by code point.\n"
    f"export const NAME_FONT_WIDTHS: Record<number, number> = {{{line}}};\n", encoding="utf-8")
print(f"wrote {out} ({len(widths)} glyphs)")
