"""Pre-render the 16 glyphs to alpha masks for the designer preview.

The designer is stdlib-only on purpose, so it cannot render a TTF at
runtime - and shipping the 1.3MB MDI font to preview 16 glyphs would be
absurd. Instead the masks are baked out here, once, and the designer
composites them over the tile colour in whatever the theme says.

Output: tools/icon_masks.py, about 25KB of base64.
"""
import base64, json, pathlib, zlib
from PIL import Image, ImageDraw, ImageFont

TOOLS = pathlib.Path(__file__).resolve().parent
HERE = TOOLS / ".iconfont"      # where make_icon_font.sh works
REPO = TOOLS.parent
TTF = HERE / "node_modules/@mdi/font/fonts/materialdesignicons-webfont.ttf"

icons = json.loads((HERE / "icons.json").read_text(encoding="utf-8"))
# Preview pixel sizes = panel size x SCALE(2). The firmware draws 28px
# and 18px glyphs; the designer shows the panel at 2x, so it needs 56
# and 36 or the icons look blocky next to crisp vector text.
SIZES = (56, 36)

out = {}
for size in SIZES:
    font = ImageFont.truetype(str(TTF), size)
    for key, v in icons.items():
        ch = chr(int(v["cp"], 16))
        img = Image.new("L", (size, size), 0)
        d = ImageDraw.Draw(img)
        # Centre the glyph in its box; MDI glyphs carry their own
        # bearing, so measure rather than assume.
        box = d.textbbox((0, 0), ch, font=font)
        d.text((-box[0] + (size - (box[2] - box[0])) // 2,
                -box[1] + (size - (box[3] - box[1])) // 2),
               ch, font=font, fill=255)
        raw = zlib.compress(img.tobytes(), 9)
        out[f"{key}_{size}"] = base64.b64encode(raw).decode("ascii")

lines = [
    '"""Alpha masks for the device icons, for the designer preview only.',
    '',
    'Generated by tools/make_icon_font.sh - do not edit by hand.',
    '',
    'Each entry is zlib-compressed 8-bit alpha, SIZE*SIZE bytes, for the',
    'same glyphs the firmware draws from src/ui/fonts/panel_icons_*.c.',
    'The designer composites these over the tile colour; the panel draws',
    'the real font. They are two renderings of one glyph set, so if they',
    'ever disagree, regenerate rather than touching either by hand.',
    '"""',
    '',
    'import base64',
    'import zlib',
    '',
    'SIZES = %r' % (list(SIZES),),
    '',
    '_MASKS = {',
]
for k, v in out.items():
    lines.append('    %r:' % k)
    for i in range(0, len(v), 96):
        lines.append('        %r' % v[i:i + 96])
    lines[-1] += ','
lines += [
    '}',
    '',
    '',
    'def mask(name, size):',
    '    """Raw alpha bytes for one glyph, or None if absent."""',
    '    blob = _MASKS.get("%s_%d" % (name, size))',
    '    if blob is None:',
    '        return None',
    '    return zlib.decompress(base64.b64decode(blob))',
    '',
]
dst = TOOLS / "icon_masks.py"
dst.write_text("\n".join(lines), encoding="utf-8")
print("wrote", dst, dst.stat().st_size, "bytes")
print("entries:", len(out))
